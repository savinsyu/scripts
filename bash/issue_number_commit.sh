#!/bin/bash

# Запрашиваем номер у пользователя
read -p "Введите номер задачи (#): " issue_number

# Проверяем, введён ли номер
if [ -z "$issue_number" ]; then
  echo "Ошибка: номер не был введён. Коммит не выполнен."
  exit 1
fi

# Формируем сообщение коммита
commit_message="#$issue_number"

# Добавляем все изменённые файлы в индекс
git add .

# Создаём коммит с сформированным сообщением
git commit -m "$commit_message"

# Отправляем изменения в удалённый репозиторий
git push

# Выводим сообщение об успешном выполнении
echo "Коммит с сообщением '$commit_message' успешно отправлен."
